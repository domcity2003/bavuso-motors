"""Write one OpenFOAM 12 case for the Bavuso V1 rev E aero study (steady RANS, k-omega SST, wall functions, moving road).

Run from v1.0 (FreeCAD python):
  ../.tools/FreeCAD_1.1.4-Windows-x86_64-py311/bin/python.exe program/tools/aero-v1-make-case.py <name> --base 0.37 [--yaw 0] [--iters 500] [--rad porous|blocked]
Case goes to program/data/aero/run/<name>/ ; run with  ../.tools/ofrun.sh program/data/aero/run/<name> ./Allrun
Patches come from program/data/aero/geometry-manifest.json (aero-v1-export.py).

Method = detailed-design/tools/aero-make-case.py (Nov 12), with these changes for the convergence study:
 * every length scale is tied to --base, so a change of --base alone refines the whole mesh by that ratio
 * the radiator cores are porous zones (Darcy-Forchheimer) instead of solid blocks, so air can flow through the pods
   (--rad blocked puts the old solid cores back). The fans are left out of the flow (open swept area).
 * rev E rider, axles and rolling radii read from the manifest.
Yaw convention: ground speed fixed at 70 mph, crosswind added: air relative to bike U=(-V,-V tan(yaw),0).
Positive yaw = wind from the rider's LEFT (air moving towards -Y).
"""
import argparse, json, math, shutil
from pathlib import Path
R=Path(__file__).resolve().parents[2]
ap=argparse.ArgumentParser()
ap.add_argument('name');ap.add_argument('--base',type=float,default=0.37);ap.add_argument('--yaw',type=float,default=0.0)
ap.add_argument('--iters',type=int,default=500);ap.add_argument('--np',type=int,default=4);ap.add_argument('--rad',default='porous')
a=ap.parse_args()
POROUS=a.rad=='porous'

V=31.2928                      # 70 mph, m/s
RHO,NU=1.225,1.5e-5
FLOOR=0.010
man=json.loads((R/'program/data/aero/geometry-manifest.json').read_text())
FRONT_AX,REAR_AX=man['axles_m']['front'],man['axles_m']['rear']
RF_ROLL,RR_ROLL=FRONT_AX[2]-FLOOR,REAR_AX[2]-FLOOR     # contact patch sits on the raised floor: surface speed = road speed there
Uy=-V*math.tan(math.radians(a.yaw))
Uvec=f'({-V:.4f} {Uy:.4f} 0)'
K=1.5*(0.01*V)**2
OM=math.sqrt(K)/(0.09**0.25*0.1)
DOM=dict(xmin=-8.0,xmax=5.5,ymin=-3.5,ymax=3.5,zmin=FLOOR,zmax=4.0)
n=[max(1,round((DOM['xmax']-DOM['xmin'])/a.base)),max(1,round((DOM['ymax']-DOM['ymin'])/a.base)),max(1,round((DOM['zmax']-DOM['zmin'])/a.base))]

allp=list(man['patches'])
fluid_only=[p for p in allp if POROUS and p.startswith(('rad_core','rad_fan'))]   # not walls in porous mode
patches=[p for p in allp if p not in fluid_only]                                   # wall patches
walls=[p for p in patches if not p.startswith('wheel')]
WALLS='"('+'|'.join(walls)+')"'
LEV={p:(5,6) for p in patches}
for p in ('rider_helmet','rider_torso_arms','rider_legs'):LEV[p]=(5,5)
FEAT={p:LEV[p][1] for p in patches}

C=R/'program/data/aero/run'/a.name
if C.exists():shutil.rmtree(C)
for d in ('system','constant','0.orig'):(C/d).mkdir(parents=True)
HDR=lambda cls,obj:f'FoamFile\n{{\n    format ascii;\n    class {cls};\n    object {obj};\n}}\n// Bavuso V1 rev E aero study, generated by program/tools/aero-v1-make-case.py\n// case {a.name}: base cell {a.base} m, yaw {a.yaw} deg, 70 mph, radiator {a.rad}\n\n'
def w(path,cls,obj,body):(C/path).write_text(HDR(cls,obj)+body,newline='\n')

w('system/blockMeshDict','dictionary','blockMeshDict',f"""convertToMeters 1;
vertices
(
    ({DOM['xmin']} {DOM['ymin']} {DOM['zmin']}) ({DOM['xmax']} {DOM['ymin']} {DOM['zmin']}) ({DOM['xmax']} {DOM['ymax']} {DOM['zmin']}) ({DOM['xmin']} {DOM['ymax']} {DOM['zmin']})
    ({DOM['xmin']} {DOM['ymin']} {DOM['zmax']}) ({DOM['xmax']} {DOM['ymin']} {DOM['zmax']}) ({DOM['xmax']} {DOM['ymax']} {DOM['zmax']}) ({DOM['xmin']} {DOM['ymax']} {DOM['zmax']})
);
blocks ( hex (0 1 2 3 4 5 6 7) ({n[0]} {n[1]} {n[2]}) simpleGrading (1 1 1) );
boundary
(
    inlet   {{ type patch;    faces ((1 2 6 5)); }}
    outlet  {{ type patch;    faces ((0 4 7 3)); }}
    ground  {{ type wall;     faces ((0 3 2 1)); }}
    sides   {{ type patch;    faces ((0 1 5 4) (3 7 6 2)); }}
    top     {{ type symmetry; faces ((4 5 6 7)); }}
);
""")

fo=''
groups={'total':'"('+'|'.join(patches)+')"','rider':'"rider_.*"','bike_body':'"('+'|'.join(p for p in walls if not p.startswith('rider'))+')"','wheels':'"wheel_.*"'}
for p in patches:groups[p]=p
for g,pat in groups.items():
    fo+=f"""    forces_{g}
    {{
        type        forces;
        libs        ("libforces.so");
        writeControl timeStep;
        writeInterval 1;
        log         {'true' if g=='total' else 'false'};
        patches     ({pat});
        rho         rhoInf;
        rhoInf      {RHO};
        CofR        (0 0 0);
    }}
"""
w('system/controlDict','dictionary','controlDict',f"""application     foamRun;
solver          incompressibleFluid;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {a.iters};
deltaT          1;
writeControl    timeStep;
writeInterval   {a.iters};
purgeWrite      1;
writeFormat     binary;
writePrecision  8;
writeCompression off;
timeFormat      general;
runTimeModifiable true;

functions
{{
{fo}    yPlus {{ type yPlus; libs ("libfieldFunctionObjects.so"); writeControl writeTime; }}
    wallShearStress {{ type wallShearStress; libs ("libfieldFunctionObjects.so"); writeControl writeTime; patches ({WALLS} wheel_front wheel_rear); }}
    flowRates
    {{
        type            surfaceFieldValue;
        libs            ("libfieldFunctionObjects.so");
        writeControl    timeStep;
        writeInterval   10;
        log             false;
        writeFields     false;
        select          patches;
        patches         (inlet outlet sides top);
        operation       sum;
        fields          (phi);
    }}
}}
""")
w('system/decomposeParDict','dictionary','decomposeParDict',f'numberOfSubdomains {a.np};   // max 4 ranks: the CPU is shared\nmethod          scotch;\n')
w('system/fvSchemes','dictionary','fvSchemes',"""ddtSchemes      { default steadyState; }
gradSchemes
{
    default         Gauss linear;
    grad(U)         cellLimited Gauss linear 1;
    grad(k)         cellLimited Gauss linear 1;
    grad(omega)     cellLimited Gauss linear 1;
}
divSchemes
{
    default         none;
    div(phi,U)      bounded Gauss linearUpwindV grad(U);
    div(phi,k)      bounded Gauss upwind;
    div(phi,omega)  bounded Gauss upwind;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear limited corrected 0.5; }
interpolationSchemes { default linear; }
snGradSchemes   { default limited corrected 0.5; }
wallDist        { method meshWave; }
""")
w('system/fvSolution','dictionary','fvSolution',"""solvers
{
    p { solver GAMG; smoother GaussSeidel; tolerance 1e-7; relTol 0.05; }
    Phi { $p; }
    "(U|k|omega)" { solver smoothSolver; smoother GaussSeidel; tolerance 1e-8; relTol 0.1; nSweeps 1; }
}
SIMPLE
{
    nNonOrthogonalCorrectors 0;
    consistent      yes;
    residualControl { p 1e-5; U 1e-6; "(k|omega)" 1e-6; }   // tighter than reachable: the run length is fixed
}
potentialFlow { nNonOrthogonalCorrectors 10; }
relaxationFactors { equations { U 0.7; "(k|omega)" 0.6; } }
cache { grad(U); }
""")
allg=allp if not POROUS else allp
geo=''.join(f'    {p:17s} {{ type triSurfaceMesh; file "{p}.stl"; }}\n' for p in allp)
feat=''.join(f'        {{ file "{p}.eMesh"; level {FEAT[p]}; }}\n' for p in patches)
ref=''.join(f'        {p:17s} {{ level ({LEV[p][0]} {LEV[p][1]}); patchInfo {{ type wall; }} }}\n' for p in patches)
corereg=''.join(f'        {p:17s} {{ mode inside; level 6; }}\n' for p in fluid_only if p.startswith('rad_core'))
sfeat=[p for p in allp]
w('system/snappyHexMeshDict','dictionary','snappyHexMeshDict',f"""castellatedMesh true;
snap            true;
addLayers       false;   // wall functions; y+ is reported, not imposed
geometry
{{
{geo}    nearBox  {{ type searchableBox; min (-2.4 -1.2 0.0); max (2.6 1.2 2.1); }}
    wakeBox  {{ type searchableBox; min (-1.4 -0.9 0.0); max (2.2 0.9 1.95); }}
    farWake  {{ type searchableBox; min (-5.0 -1.8 0.0); max (2.8 1.8 2.6); }}
}}
castellatedMeshControls
{{
    maxLocalCells       8000000;
    maxGlobalCells      40000000;
    minRefinementCells  10;
    maxLoadUnbalance    0.10;
    nCellsBetweenLevels 3;
    features
    (
{feat}    );
    refinementSurfaces
    {{
{ref}    }}
    resolveFeatureAngle 30;
    refinementRegions
    {{
        farWake {{ mode inside; level 1; }}
        nearBox {{ mode inside; level 2; }}
        wakeBox {{ mode inside; level 3; }}
{corereg}    }}
    insidePoint (4.0 2.0 2.0);
    allowFreeStandingZoneFaces true;
}}
snapControls
{{
    nSmoothPatch 3; tolerance 2.0; nSolveIter 50; nRelaxIter 5;
    nFeatureSnapIter 10; implicitFeatureSnap false; explicitFeatureSnap true; multiRegionFeatureSnap false;
}}
addLayersControls
{{
    relativeSizes true; layers {{}} expansionRatio 1.2; finalLayerThickness 0.3; minThickness 0.1; nGrow 0;
    featureAngle 120; nRelaxIter 3; nSmoothSurfaceNormals 1; nSmoothNormals 3; nSmoothThickness 10;
    maxFaceThicknessRatio 0.5; maxThicknessToMedialRatio 0.3; minMedialAxisAngle 90; nBufferCellsNoExtrude 0; nLayerIter 50;
}}
meshQualityControls
{{
    maxNonOrtho 65; maxBoundarySkewness 20; maxInternalSkewness 4; maxConcave 80; minVol 1e-13; minTetQuality 1e-15;
    minArea -1; minTwist 0.02; minDeterminant 0.001; minFaceWeight 0.05; minVolRatio 0.01; minTriangleTwist -1;
    nSmoothScale 4; errorReduction 0.75;
    relaxed {{ maxNonOrtho 75; }}
}}
mergeTolerance 1e-6;
""")
w('system/surfaceFeaturesDict','dictionary','surfaceFeaturesDict',
  'surfaces ('+' '.join(f'"{p}.stl"' for p in patches)+');\nincludedAngle   150;\nsubsetFeatures { nonManifoldEdges no; openEdges yes; }\nwriteObj        no;\n')

# ---- radiator cores as porous zones
if POROUS:
    # estimated core resistance: dP = 13 v + 2.2 v^2 Pa (v = face-normal velocity m/s), 28 mm deep, louvered-fin class (ESTIMATE)
    L=0.028;A1,B1=13.0,2.2
    d=A1/L/RHO/NU;f=2*B1/L/RHO
    T=50.0   # transverse resistance multiplier (flow forced through the thickness)
    act='';fvm='';cs=''
    for side,sg in (('neg',-1),('pos',1)):
        nrm=(-0.572,sg*0.820,0.0);ew=(0.820,-sg*0.572,0.0)
        act+=f"""    {{ name rad_core_{side}_set; type cellSet; action new; source surfaceToCell; file "./constant/geometry/rad_core_{side}.stl";
      outsidePoints ((4 2 2)); includeInside yes; includeOutside no; includeCut no; nearDistance -1; curvature -100; }}
    {{ name rad_core_{side}; type cellZoneSet; action new; source setToCellZone; set rad_core_{side}_set; }}
"""
        cs+=f"""rad_core_{side}
{{
    type    cartesian;
    origin  (0 0 0);
    coordinateRotation {{ type axesRotation; e1 ({nrm[0]} {nrm[1]} {nrm[2]}); e2 ({ew[0]} {ew[1]} {ew[2]}); }}
}}
"""
        fvm+=f"""rad_core_{side}
{{
    type            porosityForce;
    porosityForceCoeffs
    {{
        cellZone        rad_core_{side};
        type            DarcyForchheimer;
        d   ({d:.5g} {d*T:.5g} {d*T:.5g});
        f   ({f:.5g} {f*T:.5g} {f*T:.5g});
        coordinateSystem rad_core_{side};
    }}
}}
"""
    w('system/topoSetDict','dictionary','topoSetDict',f'actions\n(\n{act});\n')
    w('constant/coordinateSystems','dictionary','coordinateSystems',cs)
    w('constant/fvModels','dictionary','fvModels',fvm)
w('constant/momentumTransport','dictionary','momentumTransport','simulationType RAS;\nRAS { model kOmegaSST; turbulence on; printCoeffs on; }\n')
w('constant/physicalProperties','dictionary','physicalProperties',f'viscosityModel  constant;\nnu              {NU};    // air, about 20 C\n')

wf=lambda omega_,org:f'{{ type rotatingWallVelocity; origin ({org[0]} {org[1]} {org[2]}); axis (0 1 0); omega {omega_:.3f}; }}'
w('0.orig/U','volVectorField','U',f"""dimensions      [0 1 -1 0 0 0 0];
internalField   uniform {Uvec};
boundaryField
{{
    inlet       {{ type fixedValue; value uniform {Uvec}; }}
    outlet      {{ type inletOutlet; inletValue uniform (0 0 0); value uniform {Uvec}; }}
    sides       {{ type freestreamVelocity; freestreamValue uniform {Uvec}; value uniform {Uvec}; }}
    top         {{ type symmetry; }}
    ground      {{ type fixedValue; value uniform ({-V:.4f} 0 0); }}
    {WALLS} {{ type noSlip; }}
    wheel_front {wf(V/RF_ROLL,FRONT_AX)}   // V / rolling radius {RF_ROLL:.4f} m
    wheel_rear  {wf(V/RR_ROLL,REAR_AX)}   // V / rolling radius {RR_ROLL:.4f} m
    "proc.*"    {{ type processor; }}
}}
""")
w('0.orig/p','volScalarField','p',f"""dimensions      [0 2 -2 0 0 0 0];
internalField   uniform 0;
boundaryField
{{
    inlet       {{ type zeroGradient; }}
    outlet      {{ type fixedValue; value uniform 0; }}
    sides       {{ type freestreamPressure; freestreamValue uniform 0; value uniform 0; }}
    top         {{ type symmetry; }}
    ground      {{ type zeroGradient; }}
    "({'|'.join(patches)})" {{ type zeroGradient; }}
    "proc.*"    {{ type processor; }}
}}
""")
for fld,val,wall in (('k',K,'kqRWallFunction'),('omega',OM,'omegaWallFunction')):
    w(f'0.orig/{fld}','volScalarField',fld,f"""dimensions      {'[0 2 -2 0 0 0 0]' if fld=='k' else '[0 0 -1 0 0 0 0]'};
internalField   uniform {val:.4g};
boundaryField
{{
    inlet       {{ type fixedValue; value uniform {val:.4g}; }}
    outlet      {{ type inletOutlet; inletValue uniform {val:.4g}; value uniform {val:.4g}; }}
    sides       {{ type inletOutlet; inletValue uniform {val:.4g}; value uniform {val:.4g}; }}
    top         {{ type symmetry; }}
    "(ground|{'|'.join(patches)})" {{ type {wall}; value uniform {val:.4g}; }}
    "proc.*"    {{ type processor; }}
}}
""")
w('0.orig/nut','volScalarField','nut',f"""dimensions      [0 2 -1 0 0 0 0];
internalField   uniform 0;
boundaryField
{{
    "(inlet|outlet|sides)" {{ type calculated; value uniform 0; }}
    top         {{ type symmetry; }}
    "(ground|{'|'.join(patches)})" {{ type nutkWallFunction; value uniform 0; }}
    "proc.*"    {{ type processor; }}
}}
""")
(C/'case.json').write_text(json.dumps(dict(name=a.name,base_cell_m=a.base,yaw_deg=a.yaw,iters=a.iters,ranks=a.np,radiator=a.rad,
    ground_speed_ms=V,U_air=[-V,Uy,0],air_speed_ms=math.hypot(V,Uy),rho=RHO,nu=NU,blocks=n,domain=DOM,
    wheel_omega=dict(front=V/RF_ROLL,rear=V/RR_ROLL),k_in=K,omega_in=OM,patches=patches,fluid_only=fluid_only,levels=LEV),indent=1))
topo='runParallel topoSet\nrunParallel setsToZones -noFlipMap\n' if POROUS else ''
allrun=f"""#!/bin/sh
# Bavuso V1 rev E aero case {a.name} (generated). Run: ../.tools/ofrun.sh <this folder> ./Allrun
cd ${{0%/*}} || exit 1
. $WM_PROJECT_DIR/bin/tools/RunFunctions
mkdir -p constant/geometry && cp ../geometry/*.stl constant/geometry/
rm -rf 0 && cp -r 0.orig 0
runApplication blockMesh
runApplication surfaceFeatures
runApplication decomposePar -copyZero
runParallel snappyHexMesh -overwrite
find . -type f -iname "*level*" -exec rm {{}} \\;
{topo}runParallel checkMesh
runParallel renumberMesh -overwrite
runParallel potentialFoam -initialiseUBCs
runParallel foamRun
runApplication reconstructPar -latestTime
runApplication foamPostProcess -latestTime -func writeCellCentres
runApplication foamToVTK -latestTime -fields '(p U yPlus wallShearStress)'
touch DONE
"""
(C/'Allrun').write_text(allrun,newline='\n')
print(f'{C}: blocks {n}, U {Uvec}, {a.iters} iterations, {a.np} ranks, radiator {a.rad}, rolling radii {RF_ROLL:.4f}/{RR_ROLL:.4f}')
